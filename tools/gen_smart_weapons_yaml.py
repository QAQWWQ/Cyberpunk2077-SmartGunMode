#!/usr/bin/env python3
"""
Generate a TweakXL YAML that converts weapon records to the Smart evolution.

Input format (TSV, one weapon record per line), as produced by a CET TweakDB dump:
    <record name>\t<item type column>\t<evolution column>\t<crosshair column>
The item type / evolution columns contain text like:
    ToTweakDBID{ hash = 0x..., length = .. --[[ ItemType.Wea_Handgun ... --]]

Usage:
    python tools/gen_smart_weapons_yaml.py --input weapons.txt --output smartgun_smart_full.yaml

Options:
    --exclude-tech   Skip records whose evolution is WeaponEvolution.Tech (recommended).
    --include-smart  Keep records that are already Smart (off by default).

Only `evolution` and `crosshair` are written. `rangedAttacks` is intentionally unchanged.
"""
import argparse
import re

TARGET_TYPES = {
    "ItemType.Wea_Handgun",
    "ItemType.Wea_Revolver",
    "ItemType.Wea_Shotgun",
    "ItemType.Wea_ShotgunDual",
    "ItemType.Wea_Rifle",
    "ItemType.Wea_AssaultRifle",
    "ItemType.Wea_SubmachineGun",
    "ItemType.Wea_LightMachineGun",
    "ItemType.Wea_HeavyMachineGun",
}

TYPE_RE = re.compile(r"(ItemType\.\w+)")
EVO_RE = re.compile(r"(WeaponEvolution\.\w+)")


def parse_line(line):
    parts = line.rstrip("\n").split("\t")
    if len(parts) < 4:
        return None
    name = parts[0].strip()
    type_match = TYPE_RE.search(parts[1])
    evo_match = EVO_RE.search(parts[2])
    if not name or not type_match or not evo_match:
        return None
    return name, type_match.group(1), evo_match.group(1)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", required=True, help="weapons TSV dump")
    parser.add_argument("--output", required=True, help="output YAML path")
    parser.add_argument("--exclude-tech", action="store_true", help="skip Tech weapons")
    parser.add_argument("--include-smart", action="store_true", help="keep already-Smart records")
    args = parser.parse_args()

    picked = []
    with open(args.input, "r", encoding="utf-8", errors="replace") as fp:
        for line in fp:
            parsed = parse_line(line)
            if parsed is None:
                continue
            name, item_type, evolution = parsed
            if item_type not in TARGET_TYPES:
                continue
            if evolution == "WeaponEvolution.Smart" and not args.include_smart:
                continue
            if args.exclude_tech and evolution == "WeaponEvolution.Tech":
                continue
            picked.append(name)

    with open(args.output, "w", encoding="utf-8", newline="\n") as out:
        out.write("# Generated by tools/gen_smart_weapons_yaml.py\n")
        out.write(f"# {len(picked)} records converted to Smart + SmartGun crosshair\n\n")
        for name in picked:
            out.write(f"{name}.evolution: WeaponEvolution.Smart\n")
            out.write(f"{name}.crosshair: Crosshairs.SmartGun\n\n")

    print(f"wrote {len(picked)} records to {args.output}")


if __name__ == "__main__":
    main()
